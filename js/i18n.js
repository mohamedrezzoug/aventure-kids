export function lineTextIn(id, x, l) {
  const e = LINES[id];
  if (!e) return '';
  let s = e[l] || '';
  const nm = k => { const n = NAMES[k]; return n ? n[l] : k; };
  if (x && typeof x === 'object') { for (const k in x) s = s.split('{' + k + '}').join(nm(x[k])); }
  else if (x) s = s.split('{x}').join(nm(x));
  return s;
}
